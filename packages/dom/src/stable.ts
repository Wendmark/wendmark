/** Ids and class names longer than this are not hand-written. */
const MAX_LENGTH = 50

/** How many classes are worth keeping as anchors. */
const MAX_CLASSES = 4

/** Shapes that mean "a tool generated this, and it will change". */
const GENERATED_PATTERNS = [
  /\d{3,}/,
  /^[a-f0-9]{8}-[a-f0-9]{4}/i,
  /-[a-f0-9]{6,}$/i,
  /^(ember|radix|mui|headlessui|react-aria|chakra|ant|rc)[-_]/i,
  /^(css|sc|emotion|jss)-/i,
  /^__/,
  /^:/,
]

/** Whether a value is plausible as a hand-written name. */
function isStableName(value: string): boolean {
  const name = value.trim()
  if (name.length < 2 || name.length > MAX_LENGTH) return false
  return !GENERATED_PATTERNS.some((pattern) => pattern.test(name))
}

/** Whether an id looks hand-written rather than generated by a framework. */
export function isStableId(id: string): boolean {
  return isStableName(id)
}

/** Whether a class name looks hand-written rather than generated by a tool. */
export function isStableClass(className: string): boolean {
  return isStableName(className)
}

/** The element's hand-written class names, in order, at most a few. */
export function stableClasses(element: Element): string[] {
  return Array.from(element.classList).filter(isStableClass).slice(0, MAX_CLASSES)
}
